"""
Data Models for Post-Care AI WhatsApp Follow-Up Agent
"""
from pydantic import BaseModel, Field
from typing import Optional, List, Dict, Any
from datetime import datetime
from enum import Enum


class TriageStatus(str, Enum):
    SAFE = "SAFE"                          # Normal recovery, no concerning symptoms
    WARNING_MONITOR = "WARNING_MONITOR"    # Moderate symptoms / missed medication / minor side effects
    CRITICAL_EMERGENCY = "CRITICAL_EMERGENCY" # Severe red flags (chest pain, acute dyspnea, extreme vitals)


class HighRiskPatientEnrollRequest(BaseModel):
    """Enroll high-risk patient with required features (name, phone number, disease)"""
    name: str = Field(..., description="Patient's Full Name (e.g. Robert Johnson)")
    phone_number: str = Field(..., description="Patient's WhatsApp phone number with country code (e.g. +15559876543 or +919876543210)")
    disease: str = Field(
        ...,
        description="Patient's primary disease/condition (e.g. 'Heart Failure', 'Type 2 Diabetes', 'COPD', 'Chronic Kidney Disease')"
    )
    patient_id: Optional[str] = Field(default=None, description="Optional Patient ID or MRN (e.g. P98421)")
    risk_score: Optional[float] = Field(default=0.82, ge=0.0, le=1.0, description="Readmission risk probability")
    medications: Optional[List[str]] = Field(
        default=[],
        description="List of prescribed discharge medications (e.g. ['Lisinopril 10mg', 'Furosemide 40mg'])"
    )
    discharge_date: Optional[datetime] = Field(default_factory=datetime.utcnow, description="Date of discharge")
    send_whatsapp_now: bool = Field(default=True, description="Immediately send initial WhatsApp welcome and check-in")

    class Config:
        json_schema_extra = {
            "example": {
                "name": "Robert Johnson",
                "phone_number": "+15559876543",
                "disease": "Heart Failure",
                "patient_id": "P98421",
                "risk_score": 0.82,
                "medications": ["Lisinopril 10mg", "Furosemide 40mg", "Carvedilol 25mg"],
                "send_whatsapp_now": True
            }
        }


class FollowUpTriggerRequest(BaseModel):
    """Trigger a scheduled disease-specific follow-up message"""
    session_id: Optional[str] = Field(None, description="Active session ID")
    phone_number: Optional[str] = Field(None, description="Patient's WhatsApp phone number")
    followup_day: int = Field(default=1, description="Post-discharge day (1, 3, 7, 14, 30)")
    custom_note: Optional[str] = Field(None, description="Optional custom instruction for the AI agent")

    class Config:
        json_schema_extra = {
            "example": {
                "phone_number": "+15559876543",
                "followup_day": 3,
                "custom_note": "Ask patient if they have checked their weight this morning."
            }
        }


class AgentChatRequest(BaseModel):
    """Direct message test for AI Agent"""
    phone_number: Optional[str] = None
    session_id: Optional[str] = None
    patient_message: str = Field(..., description="Message from patient via WhatsApp")

    class Config:
        json_schema_extra = {
            "example": {
                "phone_number": "+15559876543",
                "patient_message": "Hi, I feel a little dizzy when standing up and my feet look a bit swollen."
            }
        }


class AgentChatResponse(BaseModel):
    """Response generated by Groq AI Agent with triage assessment"""
    session_id: str
    patient_name: str
    phone_number: str
    disease: str
    patient_message: str
    agent_reply: str
    triage_status: TriageStatus
    red_flags_detected: List[str] = []
    extracted_vitals: Dict[str, Any] = {}
    whatsapp_status: str = Field(default="SENT", description="'SENT' via Meta API or 'SIMULATED'")
    care_team_notified: bool = False
    timestamp: datetime = Field(default_factory=datetime.utcnow)


class AgentSessionResponse(BaseModel):
    """Details of active follow-up session"""
    session_id: str
    patient_id: Optional[str]
    patient_name: str
    phone_number: str
    disease: str
    risk_score: float
    status: str
    messages_count: int
    created_at: datetime
    last_interaction_at: datetime
    conversation_history: List[Dict[str, Any]] = []


class WhatsAppWebhookPayload(BaseModel):
    """Standard Meta WhatsApp Cloud API Webhook payload"""
    object: Optional[str] = None
    entry: Optional[List[Dict[str, Any]]] = None
